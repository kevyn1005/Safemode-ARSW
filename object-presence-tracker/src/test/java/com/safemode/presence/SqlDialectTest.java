package com.safemode.presence;

import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

class SqlDialectTest {

    @Test
    void h2KeepsItsOriginalStatementsUntouched() throws SQLException {
        try (Connection h2 = DriverManager.getConnection("jdbc:h2:mem:dialect_" + UUID.randomUUID().toString().replace("-", "")
                + ";DB_CLOSE_DELAY=-1")) {
            assertEquals(SqlDialect.H2, SqlDialect.of(h2));
        }
        // lo que ya funcionaba con H2 no debe cambiar ni una palabra
        assertEquals("BIGINT AUTO_INCREMENT PRIMARY KEY", SqlDialect.H2.idColumn());
        assertEquals("TIMESTAMP", SqlDialect.H2.timestampType());
        assertEquals("MERGE INTO camera (id, name) KEY (id) VALUES (?, ?)", SqlDialect.H2.upsertCameraSql());
    }

    @Test
    void postgresUsesIdentityTimestampWithZoneAndOnConflict() {
        assertTrue(SqlDialect.POSTGRESQL.idColumn().contains("GENERATED BY DEFAULT AS IDENTITY"));
        // con TIMESTAMP sin zona, un tracker en UTC-5 y un gateway en UTC leerian el mismo instante con 5 horas de diferencia
        assertEquals("TIMESTAMP WITH TIME ZONE", SqlDialect.POSTGRESQL.timestampType());
        assertTrue(SqlDialect.POSTGRESQL.upsertCameraSql().contains("ON CONFLICT (id) DO UPDATE"));
    }

    @Test
    void theStoreStillWorksOnH2WithTheDialectApplied() {
        try (PresenceEventStore store = PresenceEventStore.inMemory("dialect_store_" + UUID.randomUUID().toString().replace("-", ""))) {
            store.renameCamera(1, "Entrada");
            store.renameCamera(1, "Entrada principal");   // el upsert cambia el nombre, no duplica la fila
            assertEquals("Entrada principal", store.cameraName(1));
            assertEquals("CAM 2", store.cameraName(2));
        }
    }
}
