package com.safemode.presence;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Las pocas diferencias de SQL entre las dos bases que soportan {@link PresenceEventStore} y el AlertStore:
 * <ul>
 *   <li>{@link #H2}: la de siempre (archivo local o servidor del compose). Sus instrucciones NO cambian: nada de lo que ya
 *       funcionaba se toca.</li>
 *   <li>{@link #POSTGRESQL}: la base real del compose de persistencia (ADR 0005). Se elige sola por el JDBC de
 *       {@code SAFEMODE_DB_URL} ({@code jdbc:postgresql://...}).</li>
 * </ul>
 * Lo demas del SQL de los almacenes (SELECT, UPDATE, {@code ALTER TABLE ... ADD COLUMN IF NOT EXISTS}, {@code LIMIT},
 * {@code TRUNCATE ... RESTART IDENTITY}) es igual en las dos.
 */
public enum SqlDialect {

    H2("BIGINT AUTO_INCREMENT PRIMARY KEY", "TIMESTAMP",
            "MERGE INTO camera (id, name) KEY (id) VALUES (?, ?)"),

    /**
     * El tipo de la hora es {@code TIMESTAMP WITH TIME ZONE}: el tracker corre en el computador (Windows, hora de Colombia) y el
     * gateway en un contenedor (UTC). Con {@code TIMESTAMP} sin zona, PostgreSQL ignora la zona que manda el driver y el mismo
     * instante se leeria con 5 horas de diferencia.
     */
    POSTGRESQL("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "TIMESTAMP WITH TIME ZONE",
            "INSERT INTO camera (id, name) VALUES (?, ?) ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name");

    private final String idColumn;
    private final String timestampType;
    private final String upsertCameraSql;

    SqlDialect(String idColumn, String timestampType, String upsertCameraSql) {
        this.idColumn = idColumn;
        this.timestampType = timestampType;
        this.upsertCameraSql = upsertCameraSql;
    }

    /** Columna de clave primaria autonumerica (la definicion completa, desde el tipo hasta PRIMARY KEY). */
    public String idColumn() {
        return idColumn;
    }

    /** Tipo de las columnas de fecha y hora. */
    public String timestampType() {
        return timestampType;
    }

    /** "Inserta o cambia" el nombre de una camara: dos parametros, el id y el nombre. */
    public String upsertCameraSql() {
        return upsertCameraSql;
    }

    /** Detecta la base por el nombre del producto que informa el driver (no por la URL, que puede ser cualquier alias). */
    public static SqlDialect of(Connection connection) {
        try {
            String product = connection.getMetaData().getDatabaseProductName();
            return product != null && product.toLowerCase().contains("postgres") ? POSTGRESQL : H2;
        } catch (SQLException e) {
            throw new IllegalStateException("No se pudo identificar el motor de la base de datos", e);
        }
    }

    /**
     * Prepara un INSERT y pide la clave generada ({@code id}). H2 mantiene su llamada de siempre; PostgreSQL devuelve todas
     * las columnas con {@code RETURN_GENERATED_KEYS}, asi que se le pide solo {@code id}.
     */
    public PreparedStatement prepareInsert(Connection connection, String sql) throws SQLException {
        return this == POSTGRESQL
                ? connection.prepareStatement(sql, new String[] {"id"})
                : connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
    }
}
