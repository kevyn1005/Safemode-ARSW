package com.safemode.access;

import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Optional;

/**
 * Operadores, puestos de vigilancia y membresias en PostgreSQL. Aqui viven las garantias que NO se programan: la clave
 * primaria impide una membresia repetida, las claves foraneas impiden un operador o un puesto que no existen, el CHECK
 * impide un rol inventado y la transaccion deja el permiso y su auditoria cambiar juntos o no cambiar. Ver
 * {@code persistencia/db/evidence.sql} para verlas fallar a proposito.
 */
public class AccessRepository implements AutoCloseable {

    /** Operadores ficticios del laboratorio; no hay autenticacion de produccion (ver ADR 0004: el login es pendiente). */
    private static final String[] SEED_SQL = {
            "INSERT INTO puesto (id, name) VALUES ('puesto-1', 'Puesto principal')",
            "INSERT INTO operator (id, email, display_name) VALUES ('ana', 'ana@safemode.test', 'Ana')",
            "INSERT INTO operator (id, email, display_name) VALUES ('luis', 'luis@safemode.test', 'Luis')",
            "INSERT INTO operator (id, email, display_name) VALUES ('marta', 'marta@safemode.test', 'Marta')",
            "INSERT INTO membership (operator_id, puesto_id, role, can_configure) VALUES ('ana', 'puesto-1', 'admin', TRUE)",
            "INSERT INTO membership (operator_id, puesto_id, role, can_configure) VALUES ('luis', 'puesto-1', 'operator', TRUE)",
            "INSERT INTO membership (operator_id, puesto_id, role, can_configure) VALUES ('marta', 'puesto-1', 'viewer', FALSE)"
    };

    private final HikariDataSource dataSource;

    /**
     * @param connectionTimeoutMs lo que se espera por una conexion antes de rendirse: con PostgreSQL caido se prefiere
     *                            fallar pronto (y responder 503) a dejar la peticion colgada
     */
    public AccessRepository(String jdbcUrl, String user, String password, int connectionTimeoutMs) {
        HikariConfig config = new HikariConfig();
        config.setJdbcUrl(jdbcUrl);
        config.setUsername(user);
        config.setPassword(password);
        config.setMaximumPoolSize(8);
        config.setConnectionTimeout(connectionTimeoutMs);
        config.setPoolName("access-pg");
        // no fallar al construir el pool si PostgreSQL aun no esta: el esquema se crea con reintentos en init()
        config.setInitializationFailTimeout(-1);
        this.dataSource = new HikariDataSource(config);
    }

    /** Crea el esquema (idempotente) y, si la base esta vacia, los datos ficticios. Reintenta mientras PostgreSQL arranca. */
    public void init(int attempts) {
        SQLException last = null;
        for (int i = 1; i <= attempts; i++) {
            try (Connection connection = dataSource.getConnection()) {
                createSchema(connection);
                seedIfEmpty(connection);
                return;
            } catch (SQLException e) {
                last = e;
                try {
                    Thread.sleep(1000);
                } catch (InterruptedException interrupted) {
                    Thread.currentThread().interrupt();
                    break;
                }
            }
        }
        throw new IllegalStateException("No se pudo preparar PostgreSQL", last);
    }

    private static void createSchema(Connection connection) throws SQLException {
        try (Statement st = connection.createStatement()) {
            st.execute("""
                CREATE TABLE IF NOT EXISTS puesto (
                    id VARCHAR(40) PRIMARY KEY,
                    name VARCHAR(80) NOT NULL
                )""");
            st.execute("""
                CREATE TABLE IF NOT EXISTS operator (
                    id VARCHAR(40) PRIMARY KEY,
                    email VARCHAR(120) NOT NULL UNIQUE,
                    display_name VARCHAR(80) NOT NULL
                )""");
            st.execute("""
                CREATE TABLE IF NOT EXISTS membership (
                    operator_id VARCHAR(40) NOT NULL REFERENCES operator(id),
                    puesto_id VARCHAR(40) NOT NULL REFERENCES puesto(id),
                    role VARCHAR(20) NOT NULL CHECK (role IN ('admin', 'operator', 'viewer')),
                    can_configure BOOLEAN NOT NULL DEFAULT FALSE,
                    PRIMARY KEY (operator_id, puesto_id)
                )""");
            // Cada cambio de permiso deja una fila, dentro de la misma transaccion que el cambio
            st.execute("""
                CREATE TABLE IF NOT EXISTS permission_audit (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    operator_id VARCHAR(40) NOT NULL,
                    puesto_id VARCHAR(40) NOT NULL,
                    action VARCHAR(10) NOT NULL CHECK (action IN ('grant', 'revoke')),
                    at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
                    FOREIGN KEY (operator_id, puesto_id) REFERENCES membership(operator_id, puesto_id)
                )""");
        }
    }

    private static void seedIfEmpty(Connection connection) throws SQLException {
        try (Statement st = connection.createStatement(); ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM puesto")) {
            rs.next();
            if (rs.getLong(1) == 0) {
                insertSeed(connection);
            }
        }
    }

    private static void insertSeed(Connection connection) throws SQLException {
        try (Statement st = connection.createStatement()) {
            for (String sql : SEED_SQL) {
                st.execute(sql);
            }
        }
    }

    /** La fuente autoritativa: una lectura por clave primaria. Una membresia que no existe es "sin permiso". */
    public Permission permission(String puesto, String operator) {
        String sql = "SELECT role, can_configure FROM membership WHERE puesto_id = ? AND operator_id = ?";
        try (Connection connection = dataSource.getConnection(); PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setString(1, puesto);
            ps.setString(2, operator);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next()
                        ? new Permission(operator, puesto, true, rs.getString(1), rs.getBoolean(2))
                        : new Permission(operator, puesto, false, null, false);
            }
        } catch (SQLException e) {
            throw new IllegalStateException("PostgreSQL no disponible", e);
        }
    }

    /**
     * Concede o revoca la configuracion y deja la auditoria, en UNA transaccion: o cambian las dos filas o no cambia
     * ninguna. Devuelve vacio si no existe la membresia.
     */
    public Optional<Permission> setCanConfigure(String puesto, String operator, boolean canConfigure) {
        try (Connection connection = dataSource.getConnection()) {
            connection.setAutoCommit(false);
            try {
                int updated;
                try (PreparedStatement ps = connection.prepareStatement(
                        "UPDATE membership SET can_configure = ? WHERE puesto_id = ? AND operator_id = ?")) {
                    ps.setBoolean(1, canConfigure);
                    ps.setString(2, puesto);
                    ps.setString(3, operator);
                    updated = ps.executeUpdate();
                }
                if (updated == 0) {
                    connection.rollback();
                    return Optional.empty();
                }
                try (PreparedStatement ps = connection.prepareStatement(
                        "INSERT INTO permission_audit (operator_id, puesto_id, action) VALUES (?, ?, ?)")) {
                    ps.setString(1, operator);
                    ps.setString(2, puesto);
                    ps.setString(3, canConfigure ? "grant" : "revoke");
                    ps.executeUpdate();
                }
                connection.commit();
            } catch (SQLException e) {
                connection.rollback();
                throw e;
            }
        } catch (SQLException e) {
            throw new IllegalStateException("PostgreSQL no disponible", e);
        }
        return Optional.of(permission(puesto, operator));
    }

    /** Vuelve a los datos ficticios del laboratorio (solo para repetir pruebas). */
    public void reset() {
        try (Connection connection = dataSource.getConnection()) {
            connection.setAutoCommit(false);
            try (Statement st = connection.createStatement()) {
                // en orden inverso a las claves foraneas
                st.execute("DELETE FROM permission_audit");
                st.execute("DELETE FROM membership");
                st.execute("DELETE FROM operator");
                st.execute("DELETE FROM puesto");
                insertSeed(connection);
                connection.commit();
            } catch (SQLException e) {
                connection.rollback();
                throw e;
            }
        } catch (SQLException e) {
            throw new IllegalStateException("PostgreSQL no disponible", e);
        }
    }

    /** Sondeo para la metrica de dependencia: responde si PostgreSQL contesta en 1 s. */
    public boolean isUp() {
        try (Connection connection = dataSource.getConnection()) {
            return connection.isValid(1);
        } catch (SQLException e) {
            return false;
        }
    }

    @Override
    public void close() {
        dataSource.close();
    }
}
